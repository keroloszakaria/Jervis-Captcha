"""Generate local English digit PCM. Build host only: Python 3 + eSpeak.
This distributes generated speech, not eSpeak code, voices, or font files.
The generated Go file is committed by the bootstrap job for offline rebuilds.
"""
from pathlib import Path
import array
import base64
import gzip
import json
import subprocess
import sys
import tempfile
import wave

samples = {}
with tempfile.TemporaryDirectory() as tmp:
    for digit in range(10):
        path = Path(tmp) / f"{digit}.wav"
        subprocess.run(["espeak", "-v", "en-us", "-s", "145", "-w", str(path), str(digit)], check=True)
        with wave.open(str(path)) as wav:
            if wav.getnchannels() != 1 or wav.getsampwidth() != 2:
                raise RuntimeError("Expected mono signed 16-bit source audio")
            rate = wav.getframerate()
            source = array.array("h", wav.readframes(wav.getnframes()))
        if sys.byteorder != "little":
            source.byteswap()
        pcm = []
        for i in range(int(len(source) * 8000 / rate)):
            lo = int(i * rate / 8000)
            hi = min(len(source), max(lo + 1, int((i + 1) * rate / 8000)))
            sample = sum(source[lo:hi]) / (hi - lo)
            pcm.append(max(0, min(255, round(sample / 256 + 128))))
        active = [i for i, value in enumerate(pcm) if abs(value - 128) > 2]
        if active:
            pcm = pcm[max(0, active[0] - 200):active[-1] + 300]
        samples[str(digit)] = base64.b64encode(bytes(pcm)).decode()
payload = base64.b64encode(gzip.compress(json.dumps(samples, separators=(",", ":")).encode(), mtime=0)).decode()
root = Path(__file__).resolve().parents[1]
(root / "internal/captcha/audio_samples.go").write_text(
    '// Code generated by scripts/audio-pack.py; generated English digit audio only.\n'
    'package captcha\n\nconst digitAudioGzip = "' + payload + '"\n', encoding="utf-8")
print(f"Bundled audio payload: {len(payload)} bytes")
